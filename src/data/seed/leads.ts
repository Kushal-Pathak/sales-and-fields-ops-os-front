export function buildLeads(
  clock: Clock,
  refs: { contacts: Contact[]; stages: Stage[]; users: User[] },
): Lead[] {
  return LEADS.map((row, index) => {
    const [
      contactIndex,
      title,
      stageIndex,
      ownerIndex,
      source,
      priority,
      value,
      nextAction,
      nextActionDays,
      createdDaysAgo,
      lastActivityHoursAgo,
    ] = row;
    return {
      id: `lead-${index + 1}`,
      contactId: at(refs.contacts, contactIndex, 'contacts').id,
      title,
      pipelineId: DEFAULT_PIPELINE_ID,
      stageId: at(refs.stages, stageIndex, 'stages').id,
      ownerId: at(refs.users, ownerIndex, 'users').id,
      source,
      priority,
      ...(value !== undefined && { value }),
      ...(nextAction !== undefined && { nextAction }),
      ...(nextActionDays !== null && { nextActionAt: clock.daysFromNow(nextActionDays, 10) }),
      lastActivityAt: clock.hoursFromNow(-lastActivityHoursAgo),
      ...clock.stamp(createdDaysAgo, lastActivityHoursAgo / 24),
    };
  });
}
